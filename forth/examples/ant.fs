( LANGTON'S ANT IN COMP80 FORTH )
( ON A CLEAR CELL THE ANT TURNS RIGHT, ON A SET ONE LEFT; )
( IT FLIPS THE CELL AND STEPS FORWARD.  AFTER ABOUT )
( 10000 STEPS OF MUDDLE IT BUILDS A HIGHWAY AND WALKS OFF )
( THE CELLS ARE QUARTER CHARACTERS ON LINES 2-31 )
HEX 8000 CONSTANT SCR DECIMAL
VARIABLE X  VARIABLE Y  VARIABLE D
( THE BIT FOR EACH QUARTER OF A CHARACTER: TL TR BL BR )
VARIABLE BITS  1 BITS !  2 ,  8 ,  4 ,
( STEPS FOR EACH DIRECTION: NORTH, EAST, SOUTH, WEST )
VARIABLE DXS  0 DXS !  1 ,  0 ,  -1 ,
VARIABLE DYS  -1 DYS !  0 ,  1 ,  0 ,
( THE CHARACTER AND BIT FOR CELL X Y, 128 ACROSS BY 64 DOWN )
: PIX ( X Y -- ADDR BIT ) DUP 1 AND DUP + >R  2 / 64 *
  SWAP DUP 1 AND R> + DUP + BITS + @ >R  2 / + SCR + R> ;
( TURN, FLIP THE CELL: 64 IS NO QUARTERS, WHICH IS A SPACE )
: FLIP ( -- ) X @ Y @ PIX  OVER C@ OVER AND IF -1 ELSE 1 THEN
  D @ + 3 AND D !  >R DUP C@ DUP 64 < IF DROP 64 THEN
  R> XOR  DUP 64 = IF DROP 32 THEN  SWAP C! ;
: STEP ( -- ) FLIP  D @ DUP + DUP DXS + @ X +!  DYS + @ Y +! ;
: IN? ( -- F ) X @ 128 <  X @ 0< 0= AND
  Y @ 64 < AND  Y @ 3 > AND ;
( IT STOPS WHEN THE ANT LEAVES THE SCREEN; A KEY CLEARS IT )
: ANT ( -- ) PAGE  0 1 AT ." LANGTON'S ANT        STEP 0"
  90 X !  28 Y !  0 D !  0
  BEGIN IN? WHILE STEP 1+
  DUP 100 MOD 0= IF 26 1 AT DUP . THEN REPEAT
  26 1 AT .  KEY DROP PAGE ;
