( SCREEN TABLES: * AND / ARE SLOW, SO A PIXEL'S CHARACTER )
( IS LOOKED UP: ROW Y GIVES THE ADDRESS OF ITS LINE, HALF X )
( ITS COLUMN )
HEX 8000 CONSTANT SCR DECIMAL
VARIABLE ROW 126 ALLOT  VARIABLE HALF 126 ALLOT
: TABLES ( -- ) 64 0 DO I 2 / 64 * SCR + I DUP + ROW + !
  LOOP 128 0 DO I 2 / I HALF + C! LOOP ;
TABLES
( FLIP XORS A CHARACTER'S QUARTERS: DRAWING TWICE RUBS OUT )
: FLIP ( MASK ADDR -- ) SWAP OVER C@ 15 AND XOR
  DUP IF 64 + ELSE DROP 32 THEN SWAP C! ;
( A BALL IS 2 BY 2 PIXELS: ONE CHARACTER, OR HALVES OF TWO, )
( OR QUARTERS OF FOUR, BY WHETHER X AND Y ARE ODD )
: BALL ( X Y -- ) OVER 1 AND OVER 1 AND >R >R
  DUP + ROW + @ SWAP HALF + C@ +  R> IF R> IF
  4 OVER FLIP 8 OVER 1+ FLIP 2 OVER 64 + FLIP 1 SWAP 65 +
  ELSE 6 OVER FLIP 9 SWAP 1+ THEN
  ELSE R> IF 12 OVER FLIP 3 SWAP 64 + ELSE 15 SWAP THEN
  THEN FLIP ;
6 CONSTANT N
( POSITIONS AND SPEEDS ARE IN 256THS OF A PIXEL )
VARIABLE BX 10 ALLOT  VARIABLE BY 10 ALLOT
VARIABLE VX 10 ALLOT  VARIABLE VY 10 ALLOT
: TH ( I A -- A ) SWAP DUP + + ;
VARIABLE SEED  VARIABLE SPEED  1 SPEED !
: RND ( N -- 0..N-1 ) SEED @ 31421 * 6927 + DUP SEED !
  128 / 255 AND * 256 / ;
: DRAW ( I -- ) DUP BX TH 1+ C@ SWAP BY TH 1+ C@ BALL ;
( AXIS ADDS V TO P, BOUNCING OFF LO AND HI )
VARIABLE PA  VARIABLE VA  VARIABLE LO  VARIABLE HI
: BACK ( -- ) VA @ DUP @ NEGATE SWAP ! ;
: AXIS ( PA VA LO HI -- ) HI ! LO ! VA ! PA !
  PA @ @ VA @ @ +
  DUP HI @ > IF HI @ DUP + SWAP - BACK THEN
  DUP LO @ < IF LO @ DUP + SWAP - BACK THEN  PA @ ! ;
( EACH STEP A BALL FALLS A LITTLE FASTER: GRAVITY )
: STEP ( I -- ) DUP DRAW  32 OVER VY TH +!
  DUP BX TH OVER VX TH 0 32255 AXIS
  DUP BY TH OVER VY TH 512 15871 AXIS  DRAW ;
: PAUSE ( -- K ) 0 SPEED @ 0 DO TICK OR LOOP ;
: START ( I -- ) 125 RND 256 * OVER BX TH !
  28 RND 256 * 512 + OVER BY TH !  64 RND 3 * 192 +  2 RND IF
  NEGATE THEN OVER VX TH !  64 RND 8 * 256 - OVER VY TH !
  DRAW ;
: BALLS ( -- ) PAGE  N 0 DO I START LOOP
  BEGIN N 0 DO I STEP LOOP PAUSE UNTIL PAGE ;
