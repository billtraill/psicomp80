( BARNSLEY FERN AND CHAOS GAME IN COMP80 FORTH )
( FERN PLOTS 5000 POINTS: EACH IS THE LAST ONE MOVED BY ONE )
( OF FOUR SHRINKING MAPS, PICKED AT RANDOM, AND THE POINTS )
( FILL IN A FERN.  CHAOS MOVES A POINT HALF WAY TO A CORNER )
( OF A TRIANGLE PICKED AT RANDOM, AND A SIERPINSKI TRIANGLE )
( APPEARS.  A KEY CLEARS EACH )
HEX 8000 CONSTANT SCR DECIMAL
( SCREEN TABLES: * AND / ARE SLOW, SO A PIXEL'S CHARACTER )
( IS LOOKED UP: ROW Y GIVES ITS LINE, HALF X ITS COLUMN )
VARIABLE ROW 126 ALLOT  VARIABLE HALF 254 ALLOT
VARIABLE BIT 2 ALLOT
: TABLES ( -- ) 64 0 DO I 2 / 64 * SCR + I DUP + ROW + !
  LOOP 256 0 DO I 2 / I HALF + C! LOOP
  1 BIT C!  2 BIT 1+ C!  8 BIT 2 + C!  4 BIT 3 + C! ;
TABLES
: SPOT ( X Y -- ADDR MASK ) DUP 1 AND DUP + >R
  DUP + ROW + @ OVER HALF + C@ +
  SWAP 1 AND R> + BIT + C@ ;
: PLOT ( X Y -- ) SPOT OVER C@ 15 AND OR 64 + SWAP C! ;
( RANDOM BYTES: THE TOP BYTE OF A 16-BIT LCG )
VARIABLE SEED
: RND8 ( -- 0-255 ) SEED @ 31421 * 6927 + SEED !
  SEED 1+ C@ ;
( THE FERN, WITH 36 AS 1.0 AND THE MAPS IN HUNDREDTHS )
VARIABLE X  VARIABLE Y
: F1 ( -- ) 0 X !  Y @ 16 * 100 / Y ! ;
: F2 ( -- ) X @ 85 * Y @ 4 * + 100 /
  Y @ 85 * X @ 4 * - 100 / 58 +  Y ! X ! ;
: F3 ( -- ) X @ 20 * Y @ 26 * - 100 /
  X @ 23 * Y @ 22 * + 100 / 58 +  Y ! X ! ;
: F4 ( -- ) Y @ 28 * X @ 15 * - 100 /
  X @ 26 * Y @ 24 * + 100 / 16 +  Y ! X ! ;
( 1, 85, 7 AND 7 IN 100, AS 3, 218, 18 AND 17 IN 256 )
: STEP ( -- ) RND8 DUP 3 < IF DROP F1 ELSE DUP 221 < IF
  DROP F2 ELSE 239 < IF F3 ELSE F4 THEN THEN THEN ;
: FERN ( -- ) PAGE 0 1 AT ." BARNSLEY FERN"  0 X ! 0 Y !
  20 0 DO STEP LOOP  5000 0 DO STEP
  X @ 3 / 62 +  63 Y @ 6 / -  PLOT LOOP KEY DROP PAGE ;
( THE TRIANGLE'S CORNERS, IN PIXELS )
VARIABLE CX 2 ALLOT  VARIABLE CY 2 ALLOT
64 CX C!  1 CX 1+ C!  126 CX 2 + C!
4 CY C!  63 CY 1+ C!  63 CY 2 + C!
: CORNER ( -- N ) RND8 DUP 85 < IF DROP 0 ELSE
  170 < IF 1 ELSE 2 THEN THEN ;
VARIABLE CC
: CHAOS ( -- ) PAGE 0 1 AT ." CHAOS GAME"  64 30
  6000 0 DO CORNER CC !  CC @ CY + C@ + HALF + C@
  SWAP CC @ CX + C@ + HALF + C@ SWAP
  OVER OVER PLOT LOOP DROP DROP KEY DROP PAGE ;
