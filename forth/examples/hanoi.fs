( TOWERS OF HANOI IN COMP80 FORTH, ANIMATED )
( N HANOI MOVES N DISCS FROM THE LEFT PEG TO THE RIGHT: )
( EACH DISC LIFTS OFF, SLIDES ACROSS AND DROPS ON AGAIN )
HEX 8000 CONSTANT SCR DECIMAL
28 CONSTANT FLOOR
VARIABLE TOP  VARIABLE LIFT  VARIABLE MOVES
VARIABLE SPEED  300 SPEED !
VARIABLE K  VARIABLE X  VARIABLE Y  VARIABLE DEST
VARIABLE HT 4 ALLOT
: HT@ ( P -- ADDR ) DUP + HT + ;
: PEG ( P -- X ) 21 * 11 + ;
: AT@ ( X Y -- ADDR ) 64 * + SCR + ;
( A PEG: RIGHT HALF OF ONE CHARACTER, LEFT HALF OF THE NEXT )
: POST ( X Y -- ) AT@ 70 OVER 1- C! 73 SWAP C! ;
( DISC K IS 2K LOWER HALF BLOCKS, CENTRED ON X )
: ROW ( C -- ) X @ K @ - Y @ AT@  K @ DUP + 0 DO
  OVER OVER I + C! LOOP DROP DROP ;
: SHOW ( -- ) 76 ROW ;
: HIDE ( -- ) 32 ROW  Y @ TOP @ < 0= IF X @ Y @ POST THEN ;
: WAIT ( -- ) SPEED @ 0 DO LOOP ;
: STEP ( DX DY -- ) HIDE Y +! X +! SHOW WAIT ;
: UP ( -- ) BEGIN Y @ LIFT @ > WHILE 0 -1 STEP REPEAT ;
: ACROSS ( X -- ) BEGIN DUP X @ - DUP WHILE
  0< IF -1 ELSE 1 THEN 0 STEP REPEAT DROP DROP ;
: DOWN ( Y -- ) BEGIN DUP Y @ > WHILE 0 1 STEP REPEAT DROP ;
: COUNT ( -- ) 1 MOVES +!  29 3 AT MOVES @ . ;
( MOVE DISC K, THE TOP ONE ON PEG FROM, ONTO PEG TO )
: MOVE ( K FROM TO -- ) DEST !  DUP PEG X !
  HT@ DUP @ FLOOR SWAP - Y !  -1 SWAP +!  K !
  UP  DEST @ PEG ACROSS
  DEST @ HT@ DUP @ 1+ DUP ROT !  FLOOR SWAP - DOWN  COUNT ;
( THE TWO PEGS GO ON THE STACK AS FROM * 3 + TO, )
( AND THE THIRD IS 3 - FROM - TO )
: SRC ( FT -- P ) 3 / ;
: DST ( FT -- P ) 3 MOD ;
: VIA ( FT -- P ) DUP SRC SWAP DST + 3 SWAP - ;
: TOVIA ( FT -- FT ) DUP SRC 3 * SWAP VIA + ;
: FROMVIA ( FT -- FT ) DUP VIA 3 * SWAP DST + ;
( N-1 DISCS OUT OF THE WAY, DISC N ACROSS, N-1 BACK ON TOP )
: HAN ( N FT -- ) OVER 0= IF DROP DROP EXIT THEN
  OVER 1- OVER TOVIA HAN
  OVER OVER DUP SRC SWAP DST MOVE
  OVER 1- OVER FROMVIA HAN  DROP DROP ;
: SETUP ( N -- ) PAGE  0 MOVES !
  21 1 AT ." TOWERS OF HANOI"  23 3 AT ." MOVES 0"
  FLOOR OVER - 1- DUP TOP !  2 - LIFT !
  64 0 DO 67 I FLOOR AT@ C! LOOP
  3 0 DO FLOOR TOP @ DO J PEG I POST LOOP LOOP
  DUP HT !  0 HT 2 + !  0 HT 4 + !  0 PEG X !
  DUP 0 DO DUP I - K !  FLOOR 1- I - Y !  SHOW LOOP DROP ;
: HANOI ( N -- ) DUP SETUP  2 HAN  0 30 AT ;
