( HILBERT CURVE IN COMP80 FORTH )
( A TURTLE DRAWS IT: EACH LEVEL IS FOUR CURVES OF THE LEVEL BELOW, )
( TURNED AND JOINED BY THREE STEPS.  LEVEL 5 IS 32 X 32 POINTS, )
( 4 CELLS APART ACROSS AND 2 DOWN, FOUR CELLS TO A CHARACTER )
HEX 8000 CONSTANT SCR DECIMAL
VARIABLE TITLE 62 ALLOT
VARIABLE X  VARIABLE Y  VARIABLE D
( THE BIT FOR EACH QUARTER OF A CHARACTER: TL TR BL BR )
VARIABLE BITS  1 BITS !  2 ,  8 ,  4 ,
( STEPS FOR EACH DIRECTION: EAST, SOUTH, WEST, NORTH )
VARIABLE DXS  1 DXS !  0 ,  0 1 - ,  0 ,
VARIABLE DYS  0 DYS !  1 ,  0 ,  0 1 - ,
: PLOT ( -- ) X @ 2 /  Y @ 2 / 64 * +  SCR +
  DUP C@ DUP 64 < IF DROP 64 THEN
  X @ 1 AND  Y @ 1 AND DUP +  +  DUP + BITS + @  OR  SWAP C! ;
: FD ( -- ) D @ 1 AND IF 2 ELSE 4 THEN 0 DO
  D @ DUP + DUP DXS + @ X +!  DYS + @ Y +!  PLOT LOOP ;
: TURN ( A -- ) D @ + 3 AND D ! ;
: HIL ( LEVEL A -- ) OVER 0= IF DROP DROP EXIT THEN
  DUP TURN  OVER 1- OVER NEGATE HIL  FD
  DUP NEGATE TURN  OVER 1- OVER HIL  FD
  OVER 1- OVER HIL  DUP NEGATE TURN  FD
  OVER 1- OVER NEGATE HIL  TURN DROP ;
( THE WHOLE SCREEN, TITLE LINE TOO; A KEY PUTS IT BACK )
: HILBERT ( -- ) 64 0 DO SCR I + C@ TITLE I + C! LOOP
  2048 0 DO 32 SCR I + C! LOOP
  1 X !  62 Y !  0 D !  PLOT  5 0 1 - HIL
  KEY DROP PAGE  64 0 DO TITLE I + C@ SCR I + C! LOOP ;
