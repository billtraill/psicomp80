( GAME OF LIFE IN COMP80 FORTH )
( 64 X 31 CELLS ON SCREEN LINES 1-31, EDGES WRAP )
( N LIFE  RUNS N GENERATIONS FROM A RANDOM BOARD )
HEX 8040 CONSTANT SCR DECIMAL
31 CONSTANT ROWS
79 CONSTANT ALIVE  ( GRAPHIC 15: A SOLID BLOCK )
VARIABLE SEED  1979 SEED !
: RND ( -- N ) SEED @ 31421 * 6927 + DUP SEED ! ;
VARIABLE NEW  ROWS 64 * 2 - ALLOT  ( NEXT GENERATION )
VARIABLE SUMS  64 ALLOT  ( COLUMN SUMS, WRAPPED ONE EACH END )
VARIABLE UP  VARIABLE MID  VARIABLE DN
: ROW ( Y -- ADDR ) 64 * SCR + ;
: ROWS! ( Y -- ) DUP ROW MID !
  DUP DUP 0= IF ROWS + THEN 1- ROW UP !
  1+ DUP ROWS = IF DROP 0 THEN ROW DN ! ;
( A CELL IS 79 OR 32, SO A SUM OF 9 IS 288 + 47 * LIVE CELLS )
: COLSUMS ( -- ) 64 0 DO UP @ I + C@  MID @ I + C@ +
  DN @ I + C@ +  SUMS 1+ I + C! LOOP
  SUMS 64 + C@ SUMS C!  SUMS 1+ C@ SUMS 65 + C! ;
( 3 LIVE IN THE 3X3 SQUARE MEANS ALIVE, 4 MEANS NO CHANGE )
: CELL ( X -- C ) DUP SUMS + DUP C@  OVER 1+ C@ +  SWAP 2 + C@ +
  DUP 429 = IF DROP DROP ALIVE EXIT THEN
  476 = IF MID @ + C@ ELSE DROP 32 THEN ;
: GEN ( -- ) NEW  ROWS 0 DO I ROWS! COLSUMS
  64 0 DO I CELL OVER C! 1+ LOOP LOOP DROP
  ROWS 64 * 0 DO NEW I + @  SCR I + ! 2 +LOOP ;
: RANDOM ( -- ) ROWS 64 * 0 DO
  RND 0< IF ALIVE ELSE 32 THEN  SCR I + C! LOOP ;
: LIFE ( N -- ) PAGE RANDOM
  0 DO 50 0 AT ." GEN " I 1+ . GEN LOOP ;
