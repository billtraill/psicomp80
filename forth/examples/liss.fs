( A POINT IS A QUARTER OF A CHARACTER: ROW Y GIVES THE )
( ADDRESS OF ITS LINE, HALF X ITS COLUMN )
HEX 8000 CONSTANT SCR DECIMAL
VARIABLE ROW 126 ALLOT  VARIABLE HALF 126 ALLOT
: TABLES ( -- ) 64 0 DO I 2 / 64 * SCR + I DUP + ROW + !
  LOOP 128 0 DO I 2 / I HALF + C! LOOP ;
TABLES
VARIABLE BITS  1 BITS !  2 ,  8 ,  4 ,
: PLOT ( X Y -- ) OVER 1 AND OVER 1 AND DUP + + DUP +
  BITS + @ >R  DUP + ROW + @ SWAP HALF + C@ +
  DUP C@ DUP 64 < IF DROP 64 THEN R> OR SWAP C! ;
( P AND R GO ROUND IN QUARTER STEPS, 1024 POINTS IN ALL )
VARIABLE P  VARIABLE R  VARIABLE DP  VARIABLE DR
VARIABLE PHASE  32 PHASE !
: AT4 ( TABLE V -- B ) 4 / 255 AND + C@ ;
: TITLE ( -- ) PAGE 0 1 AT ;
: LISS ( A B -- ) DR ! DP !  TITLE ." LISSAJOUS " DP @ .
  ." TO " DR @ .  0 P !  PHASE @ 4 * R !
  1024 0 DO XT P @ AT4  YT R @ AT4  PLOT
  DP @ P +!  DR @ R +! LOOP  KEY DROP PAGE ;
: SPIRO ( K -- ) DR !  TITLE ." SPIROGRAPH " DR @ .
  0 P !  0 R !  1024 0 DO
  XA P @ 256 + AT4  XB R @ 256 + AT4 + 64 -
  YA P @ AT4  YB R @ AT4 + 64 -  PLOT
  1 P +!  DR @ R +! LOOP  KEY DROP PAGE ;
