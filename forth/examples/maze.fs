( A MAZE IN COMP80 FORTH )
( MAZE CARVES A RANDOM MAZE OF 42 BY 29 ROOMS OUT OF A )
( SOLID SCREEN, THEN FINDS THE WAY FROM THE DOOR ON THE )
( LEFT TO THE DOOR ON THE RIGHT BY FILLING IN EVERY DEAD )
( END UNTIL ONLY THE WAY THROUGH IS LEFT.  A ROOM IS TWO )
( QUARTER CHARACTERS ACROSS AND ONE DOWN, WITH WALLS ONE )
( THICK, SO A STEP IS 3 ACROSS AND 2 DOWN AND COMES OUT )
( ABOUT SQUARE.  A KEY STARTS THE FILLING IN AND ANOTHER )
( CLEARS IT; MAZE AGAIN MAKES A NEW ONE )
HEX 8000 CONSTANT SCR DECIMAL
( SCREEN TABLES: * AND / ARE SLOW, SO A PIXEL'S CHARACTER )
( IS LOOKED UP: ROW Y GIVES ITS LINE, HALF X ITS COLUMN )
VARIABLE ROW 126 ALLOT  VARIABLE HALF 126 ALLOT
VARIABLE BIT 2 ALLOT
: TABLES ( -- ) 64 0 DO I 2 / 64 * SCR + I DUP + ROW + !
  LOOP 128 0 DO I 2 / I HALF + C! LOOP
  1 BIT C!  2 BIT 1+ C!  8 BIT 2 + C!  4 BIT 3 + C! ;
TABLES
: SPOT ( X Y -- ADDR MASK ) DUP 1 AND DUP + >R
  DUP + ROW + @ OVER HALF + C@ +
  SWAP 1 AND R> + BIT + C@ ;
: PIX? ( X Y -- F ) SPOT SWAP C@ AND ;
( DOT SETS A PIXEL WHEN PEN IS 1 AND CLEARS IT WHEN 0 )
VARIABLE PEN
: DOT ( X Y -- ) SPOT PEN @ IF OVER C@ OR ELSE -1 XOR
  OVER C@ AND THEN 15 AND DUP IF 64 + ELSE DROP 32 THEN
  SWAP C! ;
( RANDOM BYTES: THE TOP BYTE OF A 16-BIT LCG )
VARIABLE SEED
: RND8 ( -- 0-255 ) SEED @ 31421 * 6927 + SEED !
  SEED 1+ C@ ;
( DIRECTIONS 0-3 ARE RIGHT, DOWN, LEFT, UP )
VARIABLE DX  1 DX !  0 ,  -1 ,  0 ,
VARIABLE DY  0 DY !  1 ,  0 ,  -1 ,
: TH ( D TABLE -- ADDR ) SWAP DUP + + ;
( THE ROOM WE ARE IN, AND ITS LEFT PIXEL )
VARIABLE CI  VARIABLE CJ  VARIABLE PX  VARIABLE PY
: AT! ( -- ) CI @ DUP DUP + + 1+ PX !  CJ @ DUP + 5 + PY ! ;
: GO ( D -- ) DUP DX TH @ CI +!  DY TH @ CJ +!  AT! ;
: ROOM ( -- ) PX @ PY @ DOT  PX @ 1+ PY @ DOT ;
( THE WALL PIXEL ON SIDE D; WALL DRAWS THE WHOLE WALL )
: WXY ( D -- X Y ) DUP 1 AND IF 1 = IF 1 ELSE -1 THEN
  PY @ + PX @ SWAP ELSE 0= IF 2 ELSE -1 THEN PX @ +
  PY @ THEN ;
: WALL ( D -- ) DUP WXY OVER OVER DOT ROT 1 AND IF
  SWAP 1+ SWAP DOT ELSE DROP DROP THEN ;
( IS THE ROOM NEXT DOOR ON THE GRID AND STILL SOLID? )
: OK? ( N MAX -- F ) OVER > SWAP 0< 0= AND ;
: NEW? ( D -- F ) DUP DX TH @ CI @ +  SWAP DY TH @ CJ @ +
  OVER 42 OK? OVER 29 OK? AND IF DUP + 5 + SWAP DUP DUP
  + + 1+ SWAP PIX? ELSE DROP DROP 0 THEN ;
( A WAY TO A NEW ROOM, TRYING FROM A RANDOM SIDE, OR -1 )
: TRY ( -- D ) -1 RND8 3 AND  4 0 DO DUP I + 3 AND DUP
  NEW? IF ROT DROP SWAP ELSE DROP THEN LOOP DROP ;
( THE WAY BACK: ONE BYTE A STEP )
VARIABLE TOP  VARIABLE STK 1220 ALLOT
: PUSH ( D -- ) TOP @ C!  1 TOP +! ;
: POP ( -- D ) -1 TOP +!  TOP @ C@ ;
( CARVE: INTO A NEW ROOM IF THERE IS ONE, ELSE BACK A STEP )
: CARVE ( -- ) 0 PEN !  0 CI ! 0 CJ ! AT! ROOM  STK TOP !
  BEGIN TRY DUP 0< IF DROP TOP @ STK = IF EXIT THEN
  POP 2 + 3 AND GO ELSE DUP WALL DUP PUSH GO ROOM THEN
  AGAIN ;
( THE GAPS ROUND THIS ROOM, AND THE LAST ONE FOUND )
: OPEN? ( D -- F ) WXY PIX? 0= ;
: GAPS ( -- D N ) 0 0 4 0 DO I OPEN? IF SWAP DROP I SWAP
  1+ THEN LOOP ;
( A ROOM WITH ONE GAP IS A DEAD END: FILL IT AND ITS DOOR, )
( AND GO ON INTO THE NEXT ROOM, WHICH MAY BE ONE NOW )
: DEAD ( -- ) BEGIN GAPS 1 = WHILE ROOM DUP WALL GO REPEAT
  DROP ;
: SOLVE ( -- ) 1 PEN !  29 0 DO 42 0 DO I CI ! J CJ ! AT!
  DEAD LOOP LOOP ;
( A SOLID SCREEN BELOW THE TITLE, 127 BY 59 PIXELS )
: FILL ( -- ) 1984 128 DO 79 SCR I + C! LOOP
  2048 1984 DO 67 SCR I + C! LOOP
  31 2 DO 73 I 64 * 63 + SCR + C! LOOP  65 SCR 2047 + C! ;
: TITLE ( -- ) 0 1 AT ." MAZE: " ;
: MAZE ( -- ) PAGE TITLE ." CARVING" FILL  CARVE
  0 PEN !  0 5 DOT  126 61 DOT
  TITLE ." A KEY FINDS THE WAY THROUGH" KEY DROP
  TITLE ." FILLING IN THE DEAD ENDS   " SOLVE
  TITLE ." THE WAY THROUGH         " KEY DROP PAGE ;
