( ELEMENTARY CELLULAR AUTOMATA IN COMP80 FORTH )
( N RULE GROWS A ROW OF 128 CELLS FROM ONE LIVE CELL, ONE )
( GENERATION PER ROW OF QUARTER CHARACTERS DOWN THE SCREEN. )
( EACH CELL'S NEXT STATE IS BIT L*4+C*2+R OF N, WHERE L C R )
( ARE IT AND ITS NEIGHBOURS: TRY 30 RULE, 90 RULE, 110 RULE )
HEX 8000 CONSTANT SCR DECIMAL
( SCREEN TABLES: * AND / ARE SLOW, SO A PIXEL'S CHARACTER )
( IS LOOKED UP: ROW Y GIVES ITS LINE, HALF X ITS COLUMN )
VARIABLE ROW 126 ALLOT  VARIABLE HALF 126 ALLOT
VARIABLE BIT 2 ALLOT
: TABLES ( -- ) 64 0 DO I 2 / 64 * SCR + I DUP + ROW + !
  LOOP 128 0 DO I 2 / I HALF + C! LOOP
  1 BIT C!  2 BIT 1+ C!  8 BIT 2 + C!  4 BIT 3 + C! ;
TABLES
: SPOT ( X Y -- ADDR MASK ) DUP 1 AND DUP + >R
  DUP + ROW + @ OVER HALF + C@ +
  SWAP 1 AND R> + BIT + C@ ;
: PLOT ( X Y -- ) SPOT OVER C@ 15 AND OR 64 + SWAP C! ;
( RT HOLDS THE 8 BITS OF THE RULE, ONE A BYTE )
VARIABLE RT 6 ALLOT
: TABLE ( N -- ) 1 8 0 DO OVER OVER AND 0= 0= 1 AND
  I RT + C!  DUP + LOOP DROP DROP ;
( TWO ROWS OF CELLS, 1-128, WITH A DEAD CELL AT EACH END )
VARIABLE CA 128 ALLOT  VARIABLE CB 128 ALLOT
VARIABLE OLD  VARIABLE NEW  VARIABLE YY
: CLEAR ( A -- ) 130 0 DO 0 OVER I + C! LOOP DROP ;
( THE THREE CELLS SLIDE ALONG AS ONE NUMBER, 0-7 )
: GEN ( -- ) OLD @ DUP C@ DUP + SWAP 1+ C@ +
  128 0 DO DUP + 7 AND OLD @ I + 2 + C@ +
  DUP RT + C@ DUP NEW @ I + 1+ C!
  IF I YY @ PLOT THEN LOOP DROP ;
: FLIP ( -- ) OLD @ NEW @ OLD ! NEW ! ;
( A KEY CLEARS IT )
: RULE ( N -- ) DUP TABLE PAGE  0 1 AT
  ." ELEMENTARY CELLULAR AUTOMATON, RULE " .
  CA CLEAR CB CLEAR  CA OLD ! CB NEW !
  1 CA 65 + C!  64 4 PLOT
  64 5 DO I YY ! GEN FLIP LOOP KEY DROP PAGE ;
