( SIERPINSKI TRIANGLE IN COMP80 FORTH )
( PASCAL'S TRIANGLE MOD 2: ENTRY X OF ROW Y IS ODD WHEN X AND Y = X )
( 64 ROWS, EACH ENTRY TWO CELLS WIDE, FOUR CELLS TO A CHARACTER )
HEX 8000 CONSTANT SCR DECIMAL
VARIABLE TITLE 62 ALLOT
( CELL C 0-127 OF ROW Y 0-63: 1 IF SET )
: CELL ( C Y -- F ) DUP ROT + 63 -  DUP 0< IF DROP DROP 0 EXIT THEN
  2 / SWAP OVER AND = 1 AND ;
( THE GRAPHICS CHARACTER FOR COLUMN C ROW R: 64 + TL + 2TR + 4BR + 8BL )
: CH ( C R -- B ) SWAP DUP + SWAP DUP +
  OVER OVER CELL >R  OVER 1+ OVER CELL DUP + R> + >R
  OVER 1+ OVER 1+ CELL 4 * R> + >R  1+ CELL 8 * R> +
  DUP IF 64 + ELSE DROP 32 THEN ;
( THE WHOLE SCREEN, TITLE LINE TOO; A KEY PUTS IT BACK )
: SIER ( -- ) 64 0 DO SCR I + C@ TITLE I + C! LOOP
  32 0 DO 64 0 DO I J CH  J 64 * I + SCR + C! LOOP LOOP
  KEY DROP PAGE  64 0 DO TITLE I + C@ SCR I + C! LOOP ;
