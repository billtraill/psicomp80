( SNAKE IN COMP80 FORTH )
( SNAKE PLAYS: W A S D STEER, Q STOPS. EAT THE DOTS TO GROW; )
( DON'T HIT THE WALL OR YOURSELF )
( TICK WAITS ABOUT 8 MS: IT HAS THE MM57109 PUT OUT A )
( NUMBER AND HALTS FOR EACH OF ITS 12 DIGITS, SO A KEY IS )
( TAKEN RATHER THAN RESETTING THE COMP80. IT LEAVES THE )
( LAST KEY PRESSED, OR 0; LETTERS COME AS 1-26. TICK IS )
( MACHINE CODE, PUT IN THE BODY OF A VARIABLE WHOSE CODE )
( THEN JUMPS TO IT. THE DIGITS GO IN KB )
HEX
VARIABLE KB A ALLOT  VARIABLE TICK 3E ALLOT  TICK CONSTANT T0
: M, ( A B -- A+1 ) OVER C! 1+ ;
: W, ( A W -- A+2 ) OVER ! 1+ 1+ ;
T0 C5 M, D5 M, ED M, 56 M, DB M, 3 M, E6 M, 20 M, 20 M,
FA M, 3E M, 16 M, D3 M, 60 M, 3E M, 96 M, D3 M, 60 M,
E M, 0 M, 21 M, KB W, 11 M, 803F W, AF M, FB M, 76 M,
F3 M, B7 M, 28 M, 1 M, 4F M, 7D M, FE M, KB C + FF AND M,
20 M, F0 M, DB M, 3 M, E6 M, 20 M, 20 M, FA M, 3E M, 3F M,
D3 M, 60 M, 3E M, BF M, D3 M, 60 M, 3E M, 20 M, 32 M,
803F W, D1 M, 6 M, 0 M, FD M, E9 M, DROP
T0 3 - C3 M, T0 SWAP ! DECIMAL
( THE FIELD IS IN HALF CHARACTERS, ABOUT SQUARE: X 0-63, )
( Y 4-63. ROW Y GIVES THE ADDRESS OF ITS LINE )
HEX 8000 CONSTANT SCR DECIMAL
VARIABLE ROW 126 ALLOT
: TABLE ( -- ) 64 0 DO I 2 / 64 * SCR + I DUP + ROW + ! LOOP ;
TABLE
: AT@ ( X Y -- A ) DUP + ROW + @ + ;
( THE QUARTERS OF A CHARACTER THAT ARE ITS TOP OR BOTTOM )
: HM ( Y -- M ) 1 AND IF 12 ELSE 3 THEN ;
( WHAT IS AT X Y: 0 EMPTY, BOTH QUARTERS SNAKE OR WALL, )
( ONE QUARTER FOOD )
: LOOK ( X Y -- Q ) DUP HM >R AT@ C@ 15 AND R> AND ;
: PUT ( X Y P -- ) >R DUP HM R> AND >R AT@ DUP C@ 15 AND
  R> OR 64 + SWAP C! ;
: WIPE ( X Y -- ) DUP HM 15 XOR >R AT@ DUP C@ 15 AND R> AND
  DUP IF 64 + ELSE DROP 32 THEN SWAP C! ;
VARIABLE SEED
: RND ( N -- 0..N-1 ) SEED @ 31421 * 6927 + DUP SEED !
  128 / 255 AND * 256 / ;
( THE SNAKE: HEAD AT HX HY GOING DX DY. BODY HOLDS WHERE )
( IT HAS BEEN, A BYTE FOR X AND ONE FOR Y, FROM TAIL TO HEAD )
VARIABLE HX  VARIABLE HY  VARIABLE DX  VARIABLE DY
VARIABLE NDX  VARIABLE NDY  VARIABLE HEAD  VARIABLE TAIL
VARIABLE GROW  VARIABLE SCORE  VARIABLE SPEED  VARIABLE QUIT
VARIABLE BODY 1022 ALLOT
: HEADON ( -- ) HEAD @ DUP + BODY + HX @ OVER C! HY @ SWAP
  1+ C!  HEAD @ 1+ 511 AND HEAD ! ;
: TAILOFF ( -- ) TAIL @ DUP + BODY + DUP C@ SWAP 1+ C@ WIPE
  TAIL @ 1+ 511 AND TAIL ! ;
: MSG ( -- ) 14 1 AT ;
: SHOW ( -- ) 7 1 AT SCORE @ . ;
: FOOD ( -- ) BEGIN 62 RND 1+ 58 RND 5 + OVER OVER LOOK
  WHILE DROP DROP REPEAT 9 PUT ;
( EACH DOT IS WORTH A POINT AND THREE MORE PIECES OF SNAKE; )
( EVERY FOURTH ONE, THE SNAKE GOES FASTER )
: EAT ( -- ) 1 SCORE +!  SHOW  3 GROW +!  SCORE @ 4 MOD 0=
  SPEED @ 3 > AND IF -1 SPEED +! THEN  FOOD ;
: AHEAD ( -- X Y ) HX @ DX @ + HY @ DY @ + ;
( MOVE ONE PLACE ON; FALSE IF THE SNAKE HIT SOMETHING )
: MOVE ( -- F ) GROW @ IF -1 GROW +! ELSE TAILOFF THEN
  AHEAD LOOK DUP IF AHEAD SWAP DROP HM = IF 0 EXIT THEN
  -1 THEN  AHEAD HY ! HX !  HX @ HY @ 15 PUT  HEADON
  IF EAT THEN -1 ;
( A KEY: TURN, UNLESS IT WOULD GO BACK ON ITSELF )
: TURN ( DX DY -- ) OVER DX @ + 0= OVER DY @ + 0= AND
  IF DROP DROP ELSE NDY ! NDX ! THEN ;
: UPPER ( K -- C ) DUP 32 < IF 64 + THEN ;
: STEER ( K -- ) UPPER  DUP 87 = IF 0 -1 TURN THEN
  DUP 65 = IF -1 0 TURN THEN  DUP 83 = IF 0 1 TURN THEN
  DUP 68 = IF 1 0 TURN THEN  81 = IF -1 QUIT ! THEN ;
( WAIT FOR A KEY, STIRRING THE RANDOM NUMBERS MEANWHILE )
: WAITKEY ( -- K ) BEGIN 1 SEED +! TICK DUP 0= WHILE DROP
  REPEAT ;
: WALLS ( -- ) 64 0 DO I 4 15 PUT I 63 15 PUT LOOP
  63 5 DO 0 I 15 PUT 63 I 15 PUT LOOP ;
: SETUP ( -- ) PAGE 1 1 AT ." SCORE 0"  WALLS
  0 HEAD !  0 TAIL !  0 GROW !  0 SCORE !  0 QUIT !
  8 SPEED !  1 DX !  0 DY !  1 NDX !  0 NDY !  33 HY !
  4 0 DO 28 I + HX !  HX @ HY @ 15 PUT  HEADON LOOP  FOOD
  MSG ." PRESS A KEY TO START                   "
  WAITKEY STEER
  MSG ." W A S D STEER, Q STOPS                 " ;
( EACH STEP WAITS SPEED TICKS, TAKING KEYS AS THEY COME )
: FRAME ( -- ) SPEED @ 0 DO TICK DUP IF STEER ELSE DROP THEN
  LOOP ;
( ONE GAME, UNTIL THE SNAKE HITS SOMETHING OR Q IS PRESSED )
: PLAY ( -- ) SETUP  BEGIN FRAME  NDX @ DX !  NDY @ DY !
  QUIT @ IF -1 ELSE MOVE 0= THEN UNTIL ;
: AGAIN? ( -- F )
  MSG ." GAME OVER: ANY KEY PLAYS AGAIN, Q STOPS"
  WAITKEY UPPER 81 = 0= ;
: SNAKE ( -- ) BEGIN PLAY  QUIT @ IF 0 ELSE AGAIN? THEN 0=
  UNTIL PAGE ;
