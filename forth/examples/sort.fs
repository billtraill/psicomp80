( SORTING, TO WATCH, IN COMP80 FORTH )
( SORTS DRAWS 64 RANDOM BARS AND SORTS THEM WITH A BUBBLE )
( SORT, THEN THE SAME BARS WITH QUICKSORT, COUNTING THE )
( COMPARISONS AND SWAPS OF EACH.  A KEY AT THE END CLEARS )
HEX 8000 CONSTANT SCR DECIMAL
( BAR C IS COLUMN C, UP TO 60 HALF LINES TALL FROM LINE 31; )
( CELL K OF IT IS ON LINE 31 - K.  RA HOLDS THEIR ADDRESSES )
VARIABLE RA 58 ALLOT
: TABLE ( -- ) 30 0 DO SCR 1984 + I 64 * - I DUP + RA + !
  LOOP ;
TABLE
( CELL K OF A BAR H HALF LINES TALL: FULL, BOTTOM HALF, NONE )
: CELL ( H K -- B ) DUP + 1+ OVER OVER > IF DROP DROP 79
  ELSE = IF 76 ELSE 32 THEN THEN ;
( A BAR GOING FROM ONE HEIGHT TO ANOTHER: ONLY THE CELLS )
( BETWEEN THE TWO CHANGE )
VARIABLE BC  VARIABLE BH  VARIABLE LO  VARIABLE HI
: BAR ( C OLD NEW -- ) DUP BH !  OVER OVER > IF SWAP THEN
  1+ 2 / HI !  2 / LO !  BC !  LO @ BEGIN DUP HI @ < WHILE
  BH @ OVER CELL OVER DUP + RA + @ BC @ + C! 1+ REPEAT DROP ;
VARIABLE V 126 ALLOT
: V@ ( I -- X ) DUP + V + @ ;
: V! ( X I -- ) DUP + V + ! ;
VARIABLE COL  VARIABLE CMP  VARIABLE SWP
: COUNTS ( -- ) COL @ 11 + 1 AT CMP @ .
  COL @ 21 + 1 AT SWP @ . ;
( THE COUNTS GO ON LINE 1, FROM COLUMN COL; THE NAME AFTER )
: LABEL ( COL -- ) DUP COL !  0 CMP !  0 SWP !  7 + 1 AT
  ." CMP"  COL @ 17 + 1 AT ." SWP"  COUNTS  COL @ 1 AT ;
( SWAP BARS I AND J, REDRAWING BOTH )
VARIABLE XI  VARIABLE XJ
: XCH ( I J -- ) OVER V@ XI !  DUP V@ XJ !  XI @ OVER V!
  XJ @ ROT DUP >R V!  XJ @ XI @ BAR  R> XI @ XJ @ BAR
  1 SWP +!  COUNTS ;
( IS BAR I TALLER THAN BAR J? )
: BIGGER ( I J -- F ) 1 CMP +!  V@ SWAP V@ < ;
VARIABLE SEED
: RND ( N -- 0..N-1 ) SEED @ 31421 * 6927 + DUP SEED !
  128 / 255 AND * 256 / ;
( THE SAME 64 BARS EACH TIME: THE SEED STARTS THE SAME )
: FILL ( -- ) 1979 SEED !  64 0 DO I V@ 60 RND 1+ DUP I V!
  I ROT ROT BAR LOOP ;
: CLEAR ( -- ) 64 0 DO I I V@ 0 BAR  0 I V! LOOP ;
( BUBBLE SORT: EACH PASS CARRIES THE BIGGEST BAR LEFT TO THE )
( END, SO THE NEXT PASS IS ONE SHORTER )
: BUBBLE ( -- ) 0 LABEL ." BUBBLE"  63 0 DO 63 I - 0 DO
  I I 1+ BIGGER IF I I 1+ XCH THEN LOOP COUNTS LOOP ;
( QUICKSORT: THE BARS SMALLER THAN THE LAST ONE GO TO THE )
( LEFT, IT GOES NEXT TO THEM, AND EACH SIDE IS SORTED )
VARIABLE PIV  VARIABLE NX
: PART ( LO HI -- P ) DUP V@ PIV !  OVER NX !  DUP ROT DO
  1 CMP +!  I V@ PIV @ < IF NX @ I = 0= IF NX @ I XCH THEN
  1 NX +! THEN LOOP  NX @ OVER = 0= IF NX @ OVER XCH THEN
  DROP NX @ ;
: QS ( LO HI -- ) OVER OVER < 0= IF DROP DROP EXIT THEN
  OVER OVER PART ROT OVER 1- QS 1+ SWAP QS ;
: QUICK ( -- ) 33 LABEL ." QUICK"  0 63 QS  COUNTS ;
: PAUSE ( -- ) 30000 0 DO LOOP ;
: SORTS ( -- ) PAGE  V 128 + V DO 0 I ! 2 +LOOP
  FILL PAUSE BUBBLE  PAUSE CLEAR FILL PAUSE QUICK
  KEY DROP PAGE ;
