% COLOURING A MAP OF FIVE COUNTRIES, A TO E, WITH THREE
% COLOURS, SO THAT NO TWO NEIGHBOURS ARE THE SAME COLOUR.
NEXT(RED,GREEN).
NEXT(RED,BLUE).
NEXT(GREEN,RED).
NEXT(GREEN,BLUE).
NEXT(BLUE,RED).
NEXT(BLUE,GREEN).
% A TOUCHES B, C AND D; B TOUCHES C AND E; C TOUCHES D AND E.
MAP(A,B,C,D,E) :- NEXT(A,B), NEXT(A,C), NEXT(A,D),
  NEXT(B,C), NEXT(B,E), NEXT(C,D), NEXT(C,E).
