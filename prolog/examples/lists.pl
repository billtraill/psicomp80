% LISTS.  [H:T] IS THE LIST WITH HEAD H AND TAIL T.
APPEND([],L,L).
APPEND([H:T],L,[H:R]) :- APPEND(T,L,R).
MEMBER(X,[X:?]).
MEMBER(X,[?:T]) :- MEMBER(X,T).
% REVERSE WITH AN ACCUMULATOR: THE LIST SO FAR, BACK TO FRONT.
REVERSE(L,R) :- REV(L,[],R).
REV([],A,A).
REV([H:T],A,R) :- REV(T,[H:A],R).
LENGTH([],0).
LENGTH([?:T],N) :- LENGTH(T,M), SUM(M,1,N).
