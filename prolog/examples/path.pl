% FINDING A WAY THROUGH A NETWORK OF ROADS BETWEEN TOWNS.
ROAD(ARK,BAY).
ROAD(ARK,COVE).
ROAD(BAY,DALE).
ROAD(COVE,DALE).
ROAD(DALE,ELM).
ROAD(COVE,ELM).
ROAD(ELM,FORD).
% ROADS GO BOTH WAYS.
NEAR(X,Y) :- ROAD(X,Y).
NEAR(X,Y) :- ROAD(Y,X).
% NOTIN(X,L): X IS NOT IN L.  IF IT IS, CUT AND FAIL.
NOTIN(X,L) :- MEMBER(X,L), !, FAIL.
NOTIN(?,?).
MEMBER(X,[X:?]).
MEMBER(X,[?:T]) :- MEMBER(X,T).
% GO(X,Y,V,P): P IS V AND A WAY ON FROM X TO Y, BACK TO FRONT,
% NOT THROUGH THE TOWNS IN V.
WAY(X,Y,P) :- GO(X,Y,[X],Q), REVERSE(Q,P).
GO(X,X,V,V).
GO(X,Y,V,P) :- NEAR(X,Z), NOTIN(Z,V), GO(Z,Y,[Z:V],P).
REVERSE(L,R) :- REV(L,[],R).
REV([],A,A).
REV([H:T],A,R) :- REV(T,[H:A],R).
